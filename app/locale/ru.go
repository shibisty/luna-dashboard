// ruPlural picks the form for n: 1, 21 → one; 2–4, 22–24 → few; the rest many.
func ruPlural(n int) int {
	if n < 0 {
		n = -n
	}
	switch {
	case n%10 == 1 && n%100 != 11:
		return 0
	case n%10 >= 2 && n%10 <= 4 && (n%100 < 12 || n%100 > 14):
		return 1
	default:
		return 2
	}
}
